import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { PGlite } from '@electric-sql/pglite';
import { planAgentMovement } from '../src/lib/agentMovements.ts';

test('database corrections are atomic, reject stale data and enforce permissions', async () => {
  const db = new PGlite();
  const agentId = '00000000-0000-0000-0000-000000000001';
  const adminId = '00000000-0000-0000-0000-000000000002';
  const now = '2026-11-23T10:00:00+00:00';
  try {
    await db.exec(`
      CREATE ROLE anon; CREATE ROLE authenticated;
      CREATE SCHEMA auth;
      CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql AS $$ SELECT '${adminId}'::uuid $$;
      CREATE TYPE user_role AS ENUM ('SUPER_ADMIN','ADMIN','SUPERVISOR','VIEWER','AGENT');
      CREATE TYPE payment_status AS ENUM ('PENDING','PARTIALLY_PAID','PAID','CANCELLED');
      CREATE TYPE wallet_transaction_type AS ENUM ('DEPOSIT','PAYMENT','ADJUSTMENT');
      CREATE TABLE profiles (id uuid PRIMARY KEY, full_name text, role user_role, permissions text[], deleted_at timestamptz, status text);
      CREATE TABLE agent_details (id uuid PRIMARY KEY, current_balance numeric);
      CREATE TABLE orders (id bigint PRIMARY KEY, agent_id uuid, total_amount numeric, paid_amount numeric, payment_history jsonb, payment_status payment_status, paid_at timestamptz, created_at timestamptz);
      CREATE TABLE wallet_transactions (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, agent_id uuid, amount numeric, type wallet_transaction_type, description text, locked boolean DEFAULT false, linked_order_id bigint, created_at timestamptz DEFAULT now());
      CREATE TABLE audit_logs (user_id uuid, user_name text, action text, context text, details text, previous_value text, new_value text);
      INSERT INTO profiles VALUES ('${adminId}', 'محاسب', 'ADMIN', '{EDIT_AGENTS}', NULL, 'active');
      INSERT INTO agent_details VALUES ('${agentId}', -200);
      INSERT INTO orders VALUES (1, '${agentId}', 100, 0, '[]', 'PENDING', NULL, '2026-11-01T00:00:00Z'), (2, '${agentId}', 100, 0, '[]', 'PENDING', NULL, '2026-11-02T00:00:00Z');
    `);
    await db.exec(readFileSync(new URL('../supabase/migrations/20261123143426_agent_movement_corrections.sql', import.meta.url), 'utf8'));
    let nextId = 1000;
    async function snapshot() {
      const balance = (await db.query('SELECT current_balance FROM agent_details')).rows[0].current_balance;
      const rawOrders = (await db.query('SELECT * FROM orders ORDER BY id')).rows;
      const transaction = (await db.query('SELECT to_jsonb(t) AS tx FROM wallet_transactions t LIMIT 1')).rows[0]?.tx;
      return { balance, rawOrders, transaction };
    }
    function plan(state, amount, remove = false) {
      const raw = state.transaction;
      return planAgentMovement({
        agentId, user: { id: adminId, fullName: 'محاسب' }, now, mode: 'settlement', amount, remove, paymentId: () => ++nextId,
        transaction: raw ? { ...raw, agentId: raw.agent_id, createdAt: raw.created_at, linkedOrderId: raw.linked_order_id, paymentDetails: raw.payment_details } : undefined,
        orders: state.rawOrders.map(order => ({ id: order.id, agentId: order.agent_id, totalAmount: Number(order.total_amount), paidAmount: Number(order.paid_amount), paymentHistory: order.payment_history, paymentStatus: order.payment_status, createdAt: order.created_at, paidAt: order.paid_at?.toISOString() || null }))
      });
    }
    async function save(state, change) {
      await db.query('SELECT public.save_agent_movement($1, $2, $3, $4, $5)', [agentId, state.balance, state.transaction || null, change.next, change.orderChanges]);
    }
    const empty = await snapshot();
    await save(empty, plan(empty, 250));
    let state = await snapshot();
    assert.equal(Number(state.balance), 50);
    assert.deepEqual(state.rawOrders.map(order => Number(order.paid_amount)), [100, 100]);
    assert.equal(state.transaction.amount, 250);
    const beforeEdit = state;
    await save(state, plan(state, 80));
    state = await snapshot();
    assert.equal(Number(state.balance), -120);
    assert.deepEqual(state.rawOrders.map(order => Number(order.paid_amount)), [80, 0]);
    assert.deepEqual(state.rawOrders.map(order => order.payment_status), ['PARTIALLY_PAID', 'PENDING']);
    assert.deepEqual(state.rawOrders.map(order => order.paid_at), [null, null]);
    await assert.rejects(save(beforeEdit, plan(beforeEdit, 90)), /تغيّر رصيد/);
    // A later stale invoice must roll back an earlier invoice update in the same call.
    const decrease = plan(state, 50);
    decrease.orderChanges.push({ id: 2, expected: {}, paid_amount: 0, payment_history: [] });
    await assert.rejects(save(state, decrease), /تغيّرت دفعات/);
    assert.deepEqual(await snapshot(), state);
    await db.exec("UPDATE profiles SET permissions = '{}'");
    await assert.rejects(save(state, plan(state, undefined, true)), /صلاحية/);
    await db.exec("UPDATE profiles SET permissions = '{EDIT_AGENTS}'; SELECT public.set_agent_movement_locked('1', true)");
    const locked = await snapshot();
    await assert.rejects(save(locked, { next: null, orderChanges: [] }), /مقفلة/);
    await assert.rejects(db.query("SELECT public.set_agent_movement_locked('1', false)"), /صلاحية/);
    await db.exec("UPDATE profiles SET role = 'SUPER_ADMIN'; SELECT public.set_agent_movement_locked('1', false)");
    state = await snapshot();
    await save(state, plan(state, undefined, true));
    state = await snapshot();
    assert.equal(Number(state.balance), -200);
    assert.deepEqual(state.rawOrders.map(order => Number(order.paid_amount)), [0, 0]);
    assert.equal(state.transaction, undefined);
    assert.equal((await db.query('SELECT count(*) AS count FROM audit_logs')).rows[0].count, 3);
    const receipt = planAgentMovement({ agentId, user: { id: adminId, fullName: 'محاسب' }, now, mode: 'invoice', orderId: 2, amount: 30, paymentId: () => ++nextId,
      orders: state.rawOrders.map(o => ({ id: o.id, agentId, totalAmount: Number(o.total_amount), paidAmount: 0, paymentHistory: [], paymentStatus: 'PENDING', createdAt: now })) });
    await save(state, receipt);
    state = await snapshot();
    assert.equal(Number(state.balance), -170);
    assert.deepEqual(state.rawOrders.map(o => Number(o.paid_amount)), [0, 30]);
    await save(state, plan(state, undefined, true));
    assert.equal(Number((await snapshot()).balance), -200);
    await db.exec(readFileSync(new URL('../supabase/migrations/20261125071327_protect_order_charge_reversals.sql', import.meta.url), 'utf8'));
    await db.exec(`INSERT INTO wallet_transactions(id,agent_id,amount,type,description) VALUES(93,'${agentId}',-100,'PAYMENT','شراء طلبية #21');
      INSERT INTO wallet_transactions(id,agent_id,amount,type,description,locked,payment_details) VALUES(100,'${agentId}',100,'ADJUSTMENT','عكس احتساب',true,'{"reversal":{"kind":"order_charge_reversal","transactionId":93,"orderId":21}}');`);
    for (const query of ["UPDATE wallet_transactions SET locked=false WHERE id=100", "DELETE FROM wallet_transactions WHERE id=100", "UPDATE wallet_transactions SET amount=-1 WHERE id=93", "DELETE FROM wallet_transactions WHERE id=93"]) {
      await assert.rejects(db.exec(query), /قيد عكسي/);
    }
    assert.equal((await db.query('SELECT count(*) AS count FROM wallet_transactions')).rows[0].count, 2);
    await db.exec(readFileSync(new URL('../supabase/migrations/20261125074134_atomic_agent_loss.sql', import.meta.url), 'utf8'));
    await db.query('SELECT public.record_agent_loss($1,$2,$3,$4,$5)', [agentId, -200, 10, 'خصم', false]);
    assert.equal(Number((await snapshot()).balance), -190);
    await db.query('SELECT public.record_agent_loss($1,$2,$3,$4,$5)', [agentId, -190, 20, 'ترجيع', true]);
    assert.equal(Number((await snapshot()).balance), -190);
    const refundEntries = (await db.query('SELECT amount FROM wallet_transactions ORDER BY id DESC LIMIT 2')).rows;
    assert.equal(refundEntries.reduce((sum, row) => sum + Number(row.amount), 0), 0);
    await assert.rejects(db.query('SELECT public.record_agent_loss($1,$2,$3,$4,$5)', [agentId, -200, 10, '', false]), /تغيّر/);
    await db.exec("CREATE FUNCTION fail_audit() RETURNS trigger LANGUAGE plpgsql AS $$BEGIN RAISE EXCEPTION 'audit failure'; END$$; CREATE TRIGGER fail_audit BEFORE INSERT ON audit_logs FOR EACH ROW EXECUTE FUNCTION fail_audit();");
    const countBefore = (await db.query('SELECT count(*) AS n FROM wallet_transactions')).rows[0].n;
    await assert.rejects(db.query('SELECT public.record_agent_loss($1,$2,$3,$4,$5)', [agentId, -190, 10, '', true]), /audit failure/);
    assert.equal((await db.query('SELECT count(*) AS n FROM wallet_transactions')).rows[0].n, countBefore);
  } finally {
    await db.close();
  }
});
